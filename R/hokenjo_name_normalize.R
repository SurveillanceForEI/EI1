# ============================================================
# 保健所名 表記ゆれ正規化
# ------------------------------------------------------------
# 週報データ側（hokenjo_data_sources.R の hokenjo_names、各県サイトの
# 表に実際に記載されている見出し）と、境界データ側（厚労省公式
# 「都道府県別市区町村符号及び保健所符号一覧」から抽出した保健所名）
# とで、同じ保健所を指していても表記が異なる場合があるため、
# 正規化ルール＋個別エイリアス表で対応づける。
#
# 主な表記ゆれパターン：
#   - 全角/半角スペースの有無（例:「南　部」→「南部」）
#   - 市区の有無（例:「札幌」⇔「札幌市」）
#   - 「保健所」「環境保健所」等の接尾辞（例:「岩国環境」⇔「岩国」）
#   - 「・」区切りの複合名（例:「東津軽・青森市」⇔「東津軽」+「青森市」）
#   - 共同設置の重複表記（例: 松江市・島根県共同設置松江（市）/（県））
# ============================================================

# 文字列を正規化キーに変換（比較用。表示には使わない）
normalize_hokenjo_key <- function(x) {
  x <- gsub("[ 　]+", "", x)              # 全角/半角スペース除去
  x <- gsub("（[^）]*）", "", x)           # 括弧書きの補足（例:「北毛（渋川・吾妻・利根沼田）」→「北毛」）除去
  x <- gsub("\\([^)]*\\)", "", x)          # 半角括弧版も同様に除去
  x <- gsub("保健所$", "", x)              # 「〜保健所」接尾辞除去
  x <- gsub("環境$", "", x)                # 山口県の「〜環境」接尾辞除去
  x <- gsub("共同設置.*$", "", x)          # 島根県の共同設置表記の簡略化
  x
}

# ------------------------------------------------------------
# 個別エイリアス表：正規化だけでは解決できない実質同一の組（手動確認済み）
# 各要素は c(境界データ側の名称, 週報データ側の名称)
# ------------------------------------------------------------
HOKENJO_NAME_ALIASES <- list(
  "青森県" = list(
    "青森市" = "東津軽・青森市", "東津軽" = "東津軽・青森市",
    "八戸市" = "三戸・八戸市", "三戸" = "三戸・八戸市"
  ),
  "宮城県" = list("仙台市" = "仙台"),
  "茨城県" = list(
    "日立" = "日立", "ひたちなか" = "日立"  # 週報は日立とひたちなかを合算表示
  ),
  "山梨県" = list("富士･東部" = "富士東部"),
  "鳥取県" = list("鳥取市" = "東部", "倉吉" = "中部", "米子" = "西部"),
  "島根県" = list(
    "松江市・島根県共同設置松江（市）" = "松江市",
    "松江市・島根県共同設置松江（県）" = "松江県型",
    "県央" = "県央"
  ),
  "山口県" = list(
    "下関市" = "下関", "岩国環境" = "岩国", "柳井環境" = "柳井",
    "周南環境" = "周南", "防府" = "防府", "山口環境" = "山口",
    "宇部環境" = "宇部", "長門環境" = "長門", "萩環境" = "萩"
  ),
  "沖縄県" = list("南　部" = "南部"),  # 全角スペース入りの重複表記を除去
  "和歌山県" = list("串本" = "田辺"),  # 串本は田辺保健所の支所（本所に統合して集計）
  "奈良県" = list(
    # 中和保健所は週報上「中和(東)」「中和(西)」の2列に分けて集計されるが、
    # 市町村単位での東西の公式な管轄分割は確認できなかった（厚労省の管轄区域
    # 案内には中和保健所として単一の管轄のみ記載）。誤った市町村割当を避ける
    # ため、境界データは「中和」を分割せず単一ポリゴンのまま保持する。
    "中和" = "中和(東)/中和(西)（要現地確認・境界は分割せず単一のまま）"
  )
)

# ------------------------------------------------------------
# 都道府県ごとの正規化を実行し、対応表 data.frame(pref, cw_name, report_name) を返す
# ------------------------------------------------------------
build_hokenjo_name_map <- function(cw_names_by_pref, report_names_by_pref) {
  out <- list()
  for (p in names(cw_names_by_pref)) {
    cw_names <- cw_names_by_pref[[p]]
    report_names <- report_names_by_pref[[p]]
    if (length(report_names) == 0) next

    alias <- HOKENJO_NAME_ALIASES[[p]]
    for (cwn in cw_names) {
      matched <- NA_character_
      # 1) 個別エイリアス表を優先
      if (!is.null(alias) && !is.null(alias[[cwn]])) {
        matched <- alias[[cwn]]
      } else {
        # 2) 正規化キーでの完全一致
        key <- normalize_hokenjo_key(cwn)
        hit <- report_names[normalize_hokenjo_key(report_names) == key]
        if (length(hit) >= 1) matched <- hit[1]
      }
      out[[length(out) + 1]] <- data.frame(pref = p, cw_name = cwn, report_name = matched,
                                            stringsAsFactors = FALSE)
    }
  }
  do.call(rbind, out)
}
